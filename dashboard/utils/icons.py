# Color palette matching theme.py
COLORS = {
    "primary": "#00d4ff",
    "success": "#00c853",
    "danger": "#ff5252",
    "warning": "#ffc107",
    "info": "#8899aa",
    "muted": "#4a5568",
    "white": "#ffffff",
}


def lucide(name: str, size: int = 18, color: str = "primary", cls: str = "") -> str:
    """Return an inline SVG icon from the Lucide icon set.

    Args:
        name: Icon name (e.g. 'inbox', 'dollar-sign', 'check-circle').
        size: Icon size in pixels (default 18).
        color: Color key from COLORS dict or a raw CSS color value.
        cls: Optional CSS class to add to the SVG element.

    Returns:
        HTML string with inline SVG.
    """
    svg_color = COLORS.get(color, color)
    paths = _ICON_PATHS.get(name, _ICON_PATHS.get("circle-dot", ""))
    class_attr = f' class="{cls}"' if cls else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{svg_color}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round"{class_attr}'
        f' style="display:inline-block;vertical-align:middle;flex-shrink:0">'
        f"{paths}</svg>"
    )


def icon_text(name: str, text: str, size: int = 20, color: str = "primary",
              tag: str = "span", cls: str = "") -> str:
    """Return an icon + text combo as HTML.

    Args:
        name: Lucide icon name.
        text: Text to display after the icon.
        size: Icon size in pixels (auto-scaled for heading tags).
        color: Color key or raw CSS color.
        tag: HTML wrapper tag (span, div, h2, etc.).
        cls: Optional CSS class for the wrapper.

    Returns:
        HTML string like: <span><svg ...></svg> Text</span>
    """
    # Auto-scale icon to match heading font sizes
    heading_sizes = {"h1": 36, "h2": 30, "h3": 26, "h4": 22}
    actual_size = heading_sizes.get(tag.lower(), size)
    class_attr = ' class="' + cls + '"' if cls else ""
    icon_svg = lucide(name, actual_size, color)
    return (
        '<' + tag + class_attr + ' style="display:inline-flex;align-items:center;gap:8px;">'
        + icon_svg + ' ' + text + '</' + tag + '>'
    )


